// Command schemagen registers the HTTP adapter's private JSON types for reflection.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	paths, err := filepath.Glob("*.go")
	if err != nil {
		panic(err)
	}
	var names []string
	for _, filename := range paths {
		if strings.HasSuffix(filename, "_test.go") {
			continue
		}
		f, parseErr := parser.ParseFile(token.NewFileSet(), filename, nil, 0)
		if parseErr != nil {
			panic(parseErr)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			ts, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			if sel, isDomain := ts.Type.(*ast.SelectorExpr); isDomain {
				// A wire type defined from a domain struct (type X workset.Y);
				// json.RawMessage wrappers are not structs.
				if pkg, _ := sel.X.(*ast.Ident); pkg != nil && pkg.Name != "json" {
					names = append(names, ts.Name.Name)
				}
				return false
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return false
			}
			include := ts.Name.Name == "emptyRequest" || ts.Name.Name == "emptyEvent" ||
				ts.Name.Name == "workContentNodeResponse"
			for _, field := range st.Fields.List {
				if field.Tag != nil && strings.Contains(field.Tag.Value, "json:") {
					include = true
				}
			}
			if include {
				names = append(names, ts.Name.Name)
			}
			return false
		})
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString(
		"// Code generated by schemagen; DO NOT EDIT.\n//nolint:testpackage // reflection needs private HTTP DTOs\npackage httpapi\n\nfunc wireRoots() []any { return []any{\n",
	)
	for _, name := range names {
		fmt.Fprintf(&b, "%s{},\n", name)
	}
	b.WriteString("} }\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("wire_roots_generated_test.go", src, 0o644); err != nil {
		panic(err)
	}
}
