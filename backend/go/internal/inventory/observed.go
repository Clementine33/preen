package inventory

import "context"

// ObservedAudio is one observed audio file as the inventory stores it, with the
// generation credential recorded beside it when a generation wrote that path.
// It is deliberately the storage shape: the SQL, its null handling and its
// column mapping stay with the adapter, while the mapping onto a planning fact
// belongs to the task that plans with it.
type ObservedAudio struct {
	Path    string
	Size    int64
	Mtime   int64
	Bitrate int64
	Format  string
	// Generated is the credential of the generation that last wrote this path,
	// nil when the path was never generated by this app.
	Generated *GeneratedCredential
}

// GeneratedCredential is the recorded fact of one generation: which encoder
// wrote the file and the content proxy a later plan compares against.
type GeneratedCredential struct {
	Codec       string
	BitrateKbps int
	Mode        string
	Size        int64
	Mtime       int64
}

// BitrateUpdate is one observed bitrate to write back onto an entry. The probed
// rate is an inventory fact, so it crosses to the adapter as this type.
type BitrateUpdate struct {
	Path        string
	BitrateKbps int64
}

// MediaCandidate is one inventory entry whose media facts are still
// unknown: an image without recorded dimensions, an audio file without a
// recorded duration, or an encoded one without a recorded bitrate (ADR 0013).
type MediaCandidate struct {
	Path   string
	Format string
}

// MediaFactsUpdate is the measured media facts to write back onto an entry. A
// zero field is not measured and leaves the stored value as it is, so one
// write shape covers images and audio alike.
type MediaFactsUpdate struct {
	Path        string
	Width       int
	Height      int
	DurationSec float64
	// Bitrate is in bits per second, the unit the planner's gate compares.
	Bitrate int64
}

// MediaProber measures the media facts recorded beside an entry. Both probes
// are best-effort at the call site: a file that cannot be measured keeps NULL
// facts, which the next pass tries again (enrich.go).
type MediaProber interface {
	// ImageDimensions reads only the image header, never the pixels.
	ImageDimensions(ctx context.Context, pathPosix string) (width, height int, err error)
	// AudioFacts measures the duration and the bitrate (bits per second),
	// from the header where it can; a zero is unknown.
	AudioFacts(ctx context.Context, pathPosix string) (sec float64, bitrate int64, err error)
}
